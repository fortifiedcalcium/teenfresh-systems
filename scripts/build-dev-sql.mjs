// Joins schema.sql and every numbered migration, in order, into supabase/dev-setup.sql.
// Paste that one file into the SQL Editor of a NEW, EMPTY Supabase project (the dev copy). Never run it on the live project.
//   node scripts/build-dev-sql.mjs
import fs from "node:fs";

const dir = new URL("../supabase/migrations/", import.meta.url);
const numbered = fs.readdirSync(dir).filter((f) => /^\d{3}_.+\.sql$/.test(f)).sort();
const files = ["schema.sql", ...numbered];
const out = files.map((f) => `-- ======================================================================\n-- ${f}\n-- ======================================================================\n${fs.readFileSync(new URL(f, dir), "utf8").trimEnd()}\n`).join("\n");
const header = `-- DEV SETUP: every migration in order (${files.join(", ")}).\n-- Run ONCE on a new, empty Supabase project. Do NOT run on the live project.\n-- Generated by scripts/build-dev-sql.mjs; re-run that script after adding a migration.\n\n`;
fs.writeFileSync(new URL("../supabase/dev-setup.sql", import.meta.url), header + out);
console.log(`supabase/dev-setup.sql: ${files.length} files, ${Math.round((header + out).length / 1024)} KB`);
